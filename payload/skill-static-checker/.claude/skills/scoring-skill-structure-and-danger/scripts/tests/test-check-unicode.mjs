#!/usr/bin/env node
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const S = join(dirname(fileURLToPath(import.meta.url)), "..", "check-unicode.mjs");
const D = mkdtempSync(join(process.env.TMPDIR || "/tmp", "test-check-unicode-"));
process.on("exit", () => rmSync(D, { recursive: true, force: true }));
let fail = 0;
const skill = (name, files) => { const d = join(D, name); for (const [p, c] of Object.entries(files)) { mkdirSync(dirname(join(d, p)), { recursive: true }); writeFileSync(join(d, p), c); } return d; };
const run = args => { const r = spawnSync(process.execPath, [S, ...args], { encoding: "utf8" }); let j = null; try { j = JSON.parse(r.stdout); } catch { j = null; } return { code: r.status, j }; };
const t = (name, cond) => { console.log(`${cond ? "成功" : "失敗"}: ${name}`); if (!cond) fail = 1; };
const FM = "---\nname: u\ndescription: 見本。\n---\n";
let r = run([skill("clean", { "SKILL.md": FM + "見本の文。絵文字の異体字セレクタ ❤\uFE0F は見ない。\n" })]);
t("見えない文字のない例(異体字セレクタだけを持つ例)は、終了コード 0 で、指摘が 0 件", r.code === 0 && r.j && r.j.findings.length === 0);
const tags = [..."ignore"].map(c => String.fromCodePoint(0xe0000 + c.charCodeAt(0))).join("");
const bad = skill("dirty", { "SKILL.md": "\uFEFF" + FM + `1 行目${tags}\n2 行目\u202E逆\n3 行目\u200B\n4 行目\u200B\u200C\u200D\n5 行目${"\u200B".repeat(12)}\n6 行目\u2062\n` });
r = run([bad]);
const at = n => r.j && r.j.findings.find(f => f.line === n);
t("違反の例は、終了コード 1", r.code === 1);
t("ファイルの先頭の BOM は、重さ「参考」", at(1) && at(1).severity === "参考");
t("タグ文字の隠した文は、重さ「重大」で、文を読み解く", at(5) && at(5).severity === "重大" && at(5).message.includes("ignore"));
t("向きを変える文字は、重さ「重大」", at(6) && at(6).severity === "重大" && at(6).source_severity === "HIGH");
t("幅のない文字 1 字は、重さ「注意」の LOW", at(7) && at(7).source_severity === "LOW");
t("幅のない文字 3 字の連なりは、重さ「注意」の MEDIUM", at(8) && at(8).source_severity === "MEDIUM");
t("見えない文字 12 字の連なりは、重さ「重大」の HIGH", at(9) && at(9).source_severity === "HIGH");
t("見えない演算子は、重さ「注意」の MEDIUM", at(10) && at(10).source_severity === "MEDIUM");
t("引数がないときは、終了コード 2", run([]).code === 2);
t("SKILL.md のないフォルダは、終了コード 2", run([D]).code === 2);
process.exit(fail);
