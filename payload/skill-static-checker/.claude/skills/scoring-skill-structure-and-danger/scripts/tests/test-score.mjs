#!/usr/bin/env node
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync, existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const S = join(dirname(fileURLToPath(import.meta.url)), "..", "score.mjs");
const D = mkdtempSync(join(process.env.TMPDIR || "/tmp", "test-score-"));
process.on("exit", () => rmSync(D, { recursive: true, force: true }));
let fail = 0;
const run = args => { const r = spawnSync(process.execPath, [S, ...args], { encoding: "utf8" }); let j = null; try { j = JSON.parse(r.stdout); } catch { j = null; } return { code: r.status, j }; };
const t = (name, cond) => { console.log(`${cond ? "成功" : "失敗"}: ${name}`); if (!cond) fail = 1; };
const f = (kind, severity, dimension, deduction) => ({ check: "x", item: "x", kind, severity, source_severity: "HIGH", dimension, deduction, file: "SKILL.md", line: 1, message: "x", fix: "x" });
const dir = (name, files) => { const d = join(D, name); mkdirSync(d); for (const [n, v] of Object.entries(files)) writeFileSync(join(d, n), typeof v === "string" ? v : JSON.stringify(v)); return d; };
const T = "/x/sample-skill";
let r = run([dir("clean", { "check-schema.json": { script: "check-schema", target: T, status: "済み", findings: [] }, "check-dependencies.json": { script: "check-dependencies", target: T, status: "対象なし", packages: [], findings: [] } })]);
t("指摘がないときは、終了コード 0 で、構造 100 点、両方とも合格", r.code === 0 && r.j && r.j.structure.score === 100 && r.j.structure.pass && r.j.danger.pass && r.j.skill === "sample-skill");
r = run([dir("mixed", { "a.json": { script: "check-schema", target: T, findings: [f("構造", "重大", "正しさ", 15), f("構造", "重大", "正しさ", 15)] }, "b.json": { script: "check-structure", target: T, findings: [f("構造", "注意", "見つけやすさ", 10)], metrics: [{ label: "行数", value: 1, limit: 500, unit: "行", over: false }] }, "c.json": { script: "check-secrets", target: T, findings: [f("危険", "重大", null, 0)] }, "d.json": { script: "check-harness", target: T, findings: [f("助言", "参考", null, 0)] } })]);
t("構造の点数は、分野の点数に重みをかけて足した 87 点", r.j && r.j.structure.score === 87 && r.j.structure.pass === true);
t("分野「正しさ」は、減点 30 で 70 点", r.j && r.j.structure.dimensions.find(x => x.name === "正しさ").score === 70);
t("危険に重さ「重大」が 1 件あるときは、危険が不合格", r.j && r.j.danger.pass === false && r.j.danger.counts.重大 === 1);
t("助言は、点数と合否に入れずに数える", r.j && r.j.advice.counts.参考 === 1);
t("指摘は、危険、構造、助言の順に並ぶ", r.j && r.j.findings.map(x => x.kind).join() === "危険,構造,構造,構造,助言");
t("参考の数の値を引き継ぐ", r.j && r.j.metrics.length === 1);
t("指摘があるときは、終了コード 1", r.code === 1);
r = run([dir("low", { "a.json": { script: "check-structure", target: T, findings: [f("構造", "重大", "正しさ", 120), f("構造", "注意", "見つけやすさ", 100)] } })]);
t("構造の点数が 70 点より低い 40 点のときは、構造が不合格", r.j && r.j.structure.score === 40 && r.j.structure.pass === false);
const out = join(D, "score.json");
r = run([join(D, "low"), "--out", out]);
t("--out のときは、ファイルに JSON を書く", existsSync(out) && JSON.parse(readFileSync(out, "utf8")).structure.score === 40);
t("JSON でないファイルがあるときは、終了コード 2", run([dir("broken", { "a.json": "{" })]).code === 2);
t("指摘の JSON が 1 つもないときは、終了コード 2", run([dir("empty", {})]).code === 2);
t("引数がないときは、終了コード 2", run([]).code === 2);
process.exit(fail);
