#!/usr/bin/env node
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, existsSync, readFileSync, chmodSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const S = join(dirname(fileURLToPath(import.meta.url)), "..", "check-schema.mjs");
const D = mkdtempSync(join(process.env.TMPDIR || "/tmp", "test-check-schema-"));
process.on("exit", () => rmSync(D, { recursive: true, force: true }));
let fail = 0;
const skill = (name, files) => { const d = join(D, name); for (const [p, c] of Object.entries(files)) { mkdirSync(dirname(join(d, p)), { recursive: true }); writeFileSync(join(d, p), c); } return d; };
const run = args => { const r = spawnSync(process.execPath, [S, ...args], { encoding: "utf8" }); let j = null; try { j = JSON.parse(r.stdout); } catch { j = null; } return { code: r.status, j }; };
const t = (name, cond) => { console.log(`${cond ? "成功" : "失敗"}: ${name}`); if (!cond) fail = 1; };
const items = r => (r.j ? r.j.findings.map(f => f.item) : []);
const good = skill("good-skill", { "SKILL.md": "---\nname: good-skill\ndescription: 見本の文書を読み、要約を表示する。発動する場面は、見本を調べるとき。\nmetadata:\n  version: 1.2.3\n---\n\n# 見本\n" });
let r = run([good]);
t("license を持たない合格の例は、終了コード 0 で、指摘が 0 件", r.code === 0 && r.j && r.j.findings.length === 0);
const bad = skill("bad-skill", { "SKILL.md": "\uFEFF---\nname: Bad--Claude-\ndescription: <tool>見本</tool> を読む。\nauthor: a\nauthor: b\n\tindent: x\nalwaysApply: true\n123: x\nmetadata:\n  version: 1.0\n---\n\n# 見本\n" });
r = run([bad]);
const want = ["BOM", "name の形", "name の予約語", "name とフォルダの名前", "XML のタグ", "同じキー", "タブの字下げ", "alwaysApply と globs", "キーの型", "metadata.version の形"];
t("違反の例は、終了コード 1", r.code === 1);
for (const w of want) t(`違反の例の指摘に「${w}」がある`, items(r).includes(w));
t("違反の例の指摘は、すべて区分「構造」、分野「正しさ」で減点を持つ", r.j && r.j.findings.every(f => f.kind === "構造" && f.dimension === "正しさ" && f.deduction > 0));
t("BOM の指摘は、重さ「注意」で減点 10", r.j && r.j.findings.find(f => f.item === "BOM").deduction === 10 && r.j.findings.find(f => f.item === "BOM").severity === "注意");
r = run([skill("nofm", { "SKILL.md": "# 見本\n" })]);
t("フロントマターがない例は、指摘「フロントマターの有無」を持つ", r.code === 1 && items(r).includes("フロントマターの有無"));
r = run([skill("long-desc", { "SKILL.md": `---\nname: long-desc\ndescription: ${"あ".repeat(1025)}\n---\n` })]);
t("description が 1,025 字の例は、指摘「description の字数」を持つ", items(r).includes("description の字数"));
r = run([skill("no-desc", { "SKILL.md": "---\nname: no-desc\n---\n" })]);
t("description がない例は、指摘「name と description の有無」を持つ", items(r).includes("name と description の有無"));
const out = join(D, "o.json");
r = run([good, "--out", out]);
t("--out のときは、ファイルに JSON を書く", r.code === 0 && existsSync(out) && JSON.parse(readFileSync(out, "utf8")).script === "check-schema");
const locked = skill("locked", { "SKILL.md": "---\nname: locked\n---\n" }); chmodSync(join(locked, "SKILL.md"), 0o000);
t("SKILL.md を読めないときは、指摘ありの 1 でなく、終了コード 2", run([locked]).code === 2);
chmodSync(join(locked, "SKILL.md"), 0o644);
t("引数がないときは、終了コード 2", run([]).code === 2);
t("SKILL.md のないフォルダは、終了コード 2", run([D]).code === 2);
process.exit(fail);
