#!/usr/bin/env node
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const S = join(dirname(fileURLToPath(import.meta.url)), "..", "find-similar-skills.mjs");
const D = mkdtempSync(join(process.env.TMPDIR || "/tmp", "test-find-similar-skills-"));
process.on("exit", () => rmSync(D, { recursive: true, force: true }));
let fail = 0;
const t = (name, cond) => { console.log(`${cond ? "成功" : "失敗"}: ${name}`); if (!cond) fail = 1; };
const sk = (root, name, desc) => { const d = join(D, root, name); mkdirSync(d, { recursive: true }); writeFileSync(join(d, "SKILL.md"), `---\nname: ${name}\ndescription: ${desc}\n---\n\n# ${name}\n`); return d; };
const run = args => { const r = spawnSync(process.execPath, [S, ...args], { encoding: "utf8" }); let j = null; try { j = JSON.parse(r.stdout); } catch { j = null; } return { code: r.status, j, out: r.stdout }; };
const me = sk("a", "summarizing-log", "ログのファイルを読み、エラーの行を要約して表示する。発動する場面は、ログを要約したいとき。");
sk("a", "summarizing-log-copy", "ログのファイルを読み、エラーの行を要約して表示する。発動する場面は、ログを要約したいとき。");
sk("a", "drawing-chart", "表の数を読み、棒のグラフを書く。発動する場面は、数を図にしたいとき。");
mkdirSync(join(D, "a", "not-skill"));
let r = run([me]);
t("既定では、調べるスキルの親のフォルダのスキルと比べ、調べるスキル自身とスキルでないフォルダを除く", r.code === 0 && r.j && r.j.skills.length === 2 && r.j.skills.every(s => s.name !== "summarizing-log"));
t("文字が近いスキルを先に並べる", r.j && r.j.skills[0].name === "summarizing-log-copy" && r.j.skills[0].similarity > r.j.skills[1].similarity);
t("調べるスキルの name と description を持つ", r.j && r.j.name === "summarizing-log" && r.j.description.startsWith("ログのファイル"));
sk("b", "other", "画像の大きさを変える。発動する場面は、画像を縮めたいとき。");
r = run([me, "--catalog", join(D, "b")]);
t("--catalog を付けると、その置き場のスキルと比べる", r.code === 0 && r.j && r.j.skills.length === 1 && r.j.skills[0].name === "other");
for (let i = 0; i < 61; i++) sk("c", `s${i}`, `見本 ${i} を読む。`);
r = run([me, "--catalog", join(D, "c")]);
t("比べるスキルが 60 本を超えたら、60 本だけを出し、状態を「調べきれなかった」にする", r.j && r.j.skills.length === 60 && r.j.status === "調べきれなかった" && r.j.over_limit === 1);
const out = join(D, "out.json"); r = run([me, "--out", out]);
t("--out を付けると、JSON をファイルに書く", r.code === 0 && existsSync(out));
t("--out を付けると、比べるスキルの数と状態を標準出力に 1 行で出す", r.out === "比べるスキル: 2 本、状態: 済み\n");
const m = join(D, "d", "multi"); mkdirSync(m, { recursive: true }); writeFileSync(join(m, "SKILL.md"), "---\nname: multi\ndescription: >\n  ログのファイルを読み、\n  エラーの行を要約する。\n---\n"); const m2 = join(D, "d", "nodesc"); mkdirSync(m2); writeFileSync(join(m2, "SKILL.md"), "---\nname: nodesc\n---\n");
r = run([me, "--catalog", join(D, "d")]);
t("複数行の形の description をつないで読み、description のないスキルがあれば「調べきれなかった」にする", r.j && r.j.skills.find(s => s.name === "multi").description === "ログのファイルを読み、 エラーの行を要約する。" && r.j.status === "調べきれなかった" && r.j.unreadable.length === 1);
const p = join(D, "f"); for (const [n, d] of [["plain", "description: ログのファイルを読み、\n  エラーの行を要約する。"], ["quote", "description: \"ログのファイルを読み、\n  エラーの行を要約する。"]]) { mkdirSync(join(p, n), { recursive: true }); writeFileSync(join(p, n, "SKILL.md"), `---\nname: ${n}\n${d}\n---\n`); }
const r2 = run([me, "--catalog", p]);
t("次の行に続く description をつなぎ、閉じていない引用符の description は読めないスキルにする", r2.j && r2.j.skills.find(s => s.name === "plain").description === "ログのファイルを読み、 エラーの行を要約する。" && r2.j.unreadable.length === 1 && r2.j.unreadable[0].endsWith("quote"));
t("比べるスキルに、近い順の番号「スキル <番号>」を付ける", r.j && r.j.skills.every((s, i) => s.id === `スキル${i + 1}`));
mkdirSync(join(D, "e"));
r = run([me, "--catalog", join(D, "e")]);
t("比べるスキルが 0 本なら、状態を「対象なし」にする", r.j && r.j.status === "対象なし" && r.j.skills.length === 0);
const nd = join(D, "g", "nodesc-me"); mkdirSync(nd, { recursive: true }); writeFileSync(join(nd, "SKILL.md"), "---\nname: nodesc-me\n---\n");
r = run([nd]);
t("調べるスキルの description を読めないときは、比べるスキルが 0 本でも「調べきれなかった」にする", r.code === 0 && r.j && r.j.skills.length === 0 && r.j.status === "調べきれなかった");
t("引数がないときは、終了コード 2", run([]).code === 2);
t("ない置き場を --catalog に渡すと、終了コード 2", run([me, "--catalog", join(D, "none")]).code === 2);
process.exit(fail);
