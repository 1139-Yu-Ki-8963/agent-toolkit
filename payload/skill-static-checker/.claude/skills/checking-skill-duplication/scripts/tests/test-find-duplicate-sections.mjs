#!/usr/bin/env node
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const S = join(dirname(fileURLToPath(import.meta.url)), "..", "find-duplicate-sections.mjs");
const D = mkdtempSync(join(process.env.TMPDIR || "/tmp", "test-find-duplicate-sections-"));
process.on("exit", () => rmSync(D, { recursive: true, force: true }));
let fail = 0;
const t = (name, cond) => { console.log(`${cond ? "成功" : "失敗"}: ${name}`); if (!cond) fail = 1; };
const skill = (name, files) => { const d = join(D, name); for (const [p, c] of Object.entries(files)) { mkdirSync(dirname(join(d, p)), { recursive: true }); writeFileSync(join(d, p), c); } return d; };
const run = args => { const r = spawnSync(process.execPath, [S, ...args], { encoding: "utf8" }); let j = null; try { j = JSON.parse(r.stdout); } catch { j = null; } return { code: r.status, j, out: r.stdout }; };
const A = "実行者は、届いた報告の文を返り値にし、返り値が決めた形でないときは中止して、理由と次にすることを表示する。返り値は起動した順に並べる。";
const B = "報告の HTML は、明るい画面と暗い画面の色の組を持ち、重大を赤、注意を黄土色で示して、幅の狭い画面では表を横に動かして読めるようにする。";
const C = "判定者の答えが届くまで待ち、最後の報告を起動の順に並べる。答えの形が表と違えば止めて、もう一度流してもらう。理由も添える。";
const base = { "SKILL.md": `---\nname: x\ndescription: x\n---\n\n# 見本\n\n## phase 1 読む\n\n### step 1-1 読む\n\n#### 手順\n\n${A}\n\n#### ── step 1-1 の情報 ──\n\n${A}\n\n## 色\n\n${B}\n` };
let r = run([skill("copy", { ...base, "references/写し.md": `# 写し\n\n## 写した節\n\n${A}\n`, "references/全スキル共通の決まり.md": `# 共通\n\n## 写し\n\n${A}\n` })]);
t("写した節の組を、近さ 1 で候補に出す", r.code === 0 && r.j && r.j.pairs.length === 1 && r.j.pairs[0].similarity === 1 && r.j.pairs[0].b.file === "references/写し.md");
t("候補の節の見出しは、上の見出しをつないだもの", r.j && r.j.pairs[0].a.heading === "phase 1 読む > step 1-1 読む > 手順");
t("step の情報の節と、全スキル共通の決まりを比べない", r.j && r.j.files.every(f => !f.includes("全スキル共通の決まり")) && r.j.pairs.every(p => !p.a.heading.includes("の情報")));
t("候補が上限の中なら、状態は「済み」", r.j && r.j.status === "済み" && r.j.over_limit === 0);
r = run([skill("para", { ...base, "references/言い換え.md": `# 言い換え\n\n## 言い換えた節\n\n${C}\n` })]);
t("言い換えた節と、別の話題の節は、候補に出さない", r.code === 0 && r.j && r.j.pairs.length === 0);
const many = Object.fromEntries(Array.from({ length: 9 }, (_, i) => [`references/写し${i}.md`, `# 写し\n\n## 写した節\n\n${A}\n`]));
r = run([skill("many", { ...base, ...many })]);
t("候補が 30 組を超えたら、30 組だけを出し、状態を「調べきれなかった」にする", r.j && r.j.pairs.length === 30 && r.j.status === "調べきれなかった" && r.j.over_limit === 15);
const out = join(D, "out.json"); r = run([skill("copy2", base), "--out", out]);
t("--out を付けると、JSON をファイルに書く", r.code === 0 && existsSync(out) && JSON.parse(readFileSync(out, "utf8")).script === "find-duplicate-sections");
t("--out を付けると、候補の数と状態を標準出力に 1 行で出す", r.out === "重複の候補: 0 件、状態: 済み\n");
r = run([skill("copy3", { ...base, "references/写し.md": `# 写し\n\n## 写した節\n\n${A}\n` }), "--out", join(D, "out3.json")]);
t("候補があるときは、その数を標準出力の行に出す", r.out === "重複の候補: 1 件、状態: 済み\n");
t("近さは小数 3 桁に丸め、線 0.6 以上の組だけを出す", JSON.parse(readFileSync(join(D, "out3.json"), "utf8")).pairs.every(p => p.similarity >= 0.6 && Math.round(p.similarity * 1000) === p.similarity * 1000));
r = run([skill("heads", { "SKILL.md": `---\nname: x\ndescription: x\n---\n\n## 前の節\n\n${A}\n\n# 題\n\n## 節\n\n#### 子1\n\n${A}\n\n#### 子2\n\n${A}\n` })]);
const hs = r.j ? r.j.pairs.flatMap(p => [p.a.heading, p.b.heading]) : [];
t("「#」より前の節と、段を飛ばした見出しも、上の見出しを正しくつなぐ", hs.includes("前の節") && hs.includes("節 > 子1") && hs.includes("節 > 子2"));
t("引数がないときは、終了コード 2", run([]).code === 2);
t("SKILL.md のないフォルダは、終了コード 2", run([D]).code === 2);
process.exit(fail);
